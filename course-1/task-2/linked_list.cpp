template <typename T>
class LinkedList {
 public:
  // Тип статуса большинства команд; используется для разных команд (но не для всех), чтобы не повторяться,
  //    так как у большинства команд два статуса: 1) успешно выполнена, и 2) ошибка, потому что список пустой.
  enum class COMMAND_STATUS {
    OK = 0,  // последняя команда выполнена успешно
    ERR      // список пустой
  };

  // Тип статуса команды right()
  enum class RIGHT_STATUS {
    OK = 0,        // последний right() выполнился успешно
    LIST_EMPTY,    // список пустой
    NO_NEXT_NODES  // справа от текущего узла нет узлов (некуда перемещаться)
  };

  enum class ADD_TO_EMPTY_STATUS {
    OK = 0,    // последний add_to_empty() выполнился успешно
    NOT_EMPTY  // список не пустой
  };

  enum class FIND_STATUS {
    OK = 0,             // последний find() выполнился успешно
    LIST_EMPTY,         // список пустой
    NO_SUCH_NEXT_VALUE  // справа от текущего узла нет узла с искомым значением
  };

 public:
  // команды:

  // предусловие: список не пустой
  // постусловие: курсор установлен на первый узел
  virtual void head() = 0;

  // предусловие: список не пустой
  // постусловие: курсор установлен на последний узел
  virtual void tail() = 0;

  // предусловие: список не пустой и справа ещё есть элементы
  // постусловие: курсор сдвинут на один узел вправо
  virtual void right() = 0;

  // предусловие: список не пустой
  // постусловие: новый узел с заданным значением вставлен следом за текущим узлом
  virtual void put_right(T value) = 0;

  // предусловие: список не пустой
  // постусловие: новый узел с заданным значением вставлен перед текущим узлом
  virtual void put_left(T value) = 0;

  // предусловие: список не пустой
  // постусловие: удалён текущий узел
  virtual void remove() = 0;

  // постусловие: очищен весь список
  virtual void clear() = 0;

  // предусловие: список пустой
  // постусловие: в пустой список добавлен новый узел
  virtual void add_to_empty(T value) = 0;

  // предусловие: список не пустой
  // постусловие: в хвост списка добавлен новый узел
  virtual void add_tail(T value) = 0;

  // предусловие: список не пустой
  // постусловие: значение текущего узла заменено на заданное
  virtual void replace(T value) = 0;

  // предусловие: список не пустой и справа есть один узел с искомым значением
  // постусловие: курсор установлен на следующий узел с искомым значением (по отношению к текущему узлу)
  virtual void find(T value) = 0;

  // постусловие: все узлы в списке с заданным значением удалены (даже если список пустой, то узлов с заданным значением точно не будет)
  virtual void remove_all(T value) = 0;

  // запросы:

  // предусловие: список не пустой
  virtual T get() const = 0;

  virtual int size() const = 0;

  // предусловие: список не пустой
  virtual bool is_head() const = 0;

  // предусловие: список не пустой
  virtual bool is_tail() const = 0;

  virtual bool is_value() const = 0;

  // дополнительные запросы:
  RIGHT_STATUS get_right_status() const;
  ADD_TO_EMPTY_STATUS get_add_to_empty_status() const;
  FIND_STATUS get_find_status() const;
  COMMAND_STATUS get_command_status() const;
};